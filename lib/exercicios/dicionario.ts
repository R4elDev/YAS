export function traduzirMusculo(valor: string): string {
  return MUSCULOS_PT[valor.toLowerCase()] ?? valor;
}

export function traduzirEquipamento(valor: string): string {
  return EQUIPAMENTOS_PT[valor.toLowerCase()] ?? valor;
}

export function traduzirNome(nomeEn: string): string {
  const palavras = nomeEn.toLowerCase().split(/\s+/).filter(Boolean);
  const pt = palavras.map((p) => PALAVRAS_PT[p] ?? p).join(" ");
  return pt.charAt(0).toUpperCase() + pt.slice(1);
}
